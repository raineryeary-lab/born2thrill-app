// Cross-check against the real catalog so a typo here fails loudly instead
// of silently generating nothing for a type the placement code expects.
const catalogTypes = new Set(FURNITURE_CATALOG.map((item) => item.type));
for (const type of Object.keys(PROMPTS)) {
  if (!catalogTypes.has(type)) throw new Error(`PROMPTS has type "${type}" not present in furniture-catalog.mjs.`);
}
for (const type of catalogTypes) {
  if (ALREADY_GENERATED_TYPES.has(type)) continue;
  if (!PROMPTS[type]) throw new Error(`furniture-catalog.mjs has type "${type}" with no prompt defined here.`);
}

const ITEMS = Object.entries(PROMPTS).flatMap(([type, byStyle]) => Object.entries(byStyle).map(([style, prompt]) => ({ type, style, prompt })));

async function submitTask(item) {
  const response = await fetch(`${BASE_URL}/generation/text-to-model`, {
    method: "POST",
    headers: { Authorization: `Bearer ${API_KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      prompt: item.prompt,
      negative_prompt: NEGATIVE_PROMPT,
      model: "v3.1-20260211",
      texture: false,
      pbr: false,
      geometry_quality: "detailed",
      face_limit: 30000,
      export_uv: false,
    }),
  });
  const body = await response.json();
  if (!response.ok || body.code !== 0) throw new Error(`Submit failed for ${item.type}/${item.style}: ${JSON.stringify(body)}`);
  return body.data.task_id;
}

async function pollTask(taskId, { intervalMs = 4000, timeoutMs = 5 * 60 * 1000 } = {}) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const response = await fetch(`${BASE_URL}/tasks/${taskId}`, { headers: { Authorization: `Bearer ${API_KEY}` } });
    const body = await response.json();
    if (!response.ok || body.code !== 0) throw new Error(`Task query failed for ${taskId}: ${JSON.stringify(body)}`);
    const { status, progress } = body.data;
    process.stdout.write(`  task ${taskId}: ${status} (${progress}%)\n`);
    if (status === "success") return body.data;
    if (status === "failed" || status === "cancelled") throw new Error(`Task ${taskId} ${status}: ${body.data.error_message || "no error message"}`);
    await new Promise((resolve) => setTimeout(resolve, intervalMs));
  }
  throw new Error(`Task ${taskId} timed out after ${timeoutMs}ms`);
}

async function downloadFile(url, destPath) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed (${response.status}) for ${url}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  await writeFile(destPath, buffer);
  return buffer.length;
}

const MANIFEST_PATH = path.join(OUTPUT_DIR, "full-catalog-manifest.json");
const CREDITS_PER_PIECE = 30; // measured, see header

// Anything already downloaded is kept. Re-submitting a piece that exists spends
// credits to reproduce a file we already have, and a run that dies partway
// used to mean starting over from zero.
async function readExistingManifest() {
  try {
    return JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
  } catch {
    return { items: [], failures: [] };
  }
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });

  const previous = await readExistingManifest();
  const keptItems = (previous.items ?? []).filter((item) =>
    existsSync(path.join(OUTPUT_DIR, `${item.type}__${item.style}.glb`)),
  );
  const keptLabels = new Set(keptItems.map((i) => `${i.type}__${i.style}`));

  const todo = ITEMS.filter((item) => {
    const label = `${item.type}__${item.style}`;
    return !keptLabels.has(label) && !existsSync(path.join(OUTPUT_DIR, `${label}.glb`));
  });

  const results = [];
  const failures = [];
  let totalCredits = 0;

  console.log(
    `${keptItems.length} already generated, ${todo.length} to generate ` +
      `(~${todo.length * CREDITS_PER_PIECE} credits at ${CREDITS_PER_PIECE}/piece).\n`,
  );

  if (todo.length === 0) {
    console.log("Nothing to do — every piece is already on disk.");
    return;
  }

  for (const item of todo) {
    const label = `${item.type}__${item.style}`;
    try {
      console.log(`Submitting ${label}...`);
      const taskId = await submitTask(item);
      console.log(`  task_id: ${taskId}`);
      const result = await pollTask(taskId);
      console.log(`  done, ${result.credits_consumed} credits consumed`);
      totalCredits += result.credits_consumed || 0;

      const modelPath = path.join(OUTPUT_DIR, `${label}.glb`);
      const previewPath = path.join(OUTPUT_DIR, `${label}.png`);
      const modelBytes = await downloadFile(result.output.model_url, modelPath);
      let previewBytes = 0;
      if (result.output.rendered_image_url) previewBytes = await downloadFile(result.output.rendered_image_url, previewPath);
      console.log(`  saved ${modelPath} (${modelBytes} bytes), preview ${previewBytes} bytes`);

      results.push({ type: item.type, style: item.style, task_id: taskId, credits_consumed: result.credits_consumed, model_path: modelPath, preview_path: previewBytes ? previewPath : null });
    } catch (error) {
      console.error(`  FAILED ${label}: ${error.message}`);
      failures.push({ type: item.type, style: item.style, error: error.message });
    }
  }

  // Merge rather than overwrite. Writing `results` alone meant a run where
  // everything failed (an exhausted credit balance, say) replaced a good
  // manifest with an empty one, losing the record of every earlier success
  // while the .glb files sat untouched on disk.
  const mergedItems = [...keptItems, ...results];
  const mergedLabels = new Set(mergedItems.map((i) => `${i.type}__${i.style}`));
  const mergedFailures = failures.filter(
    (f) => !mergedLabels.has(`${f.type}__${f.style}`),
  );

  await writeFile(
    MANIFEST_PATH,
    JSON.stringify(
      {
        generated_at: new Date().toISOString(),
        total_credits_consumed:
          (previous.total_credits_consumed ?? 0) + totalCredits,
        items: mergedItems,
        failures: mergedFailures,
      },
      null,
      2,
    ),
  );
  console.log(
    `\nDone. ${results.length}/${todo.length} new pieces succeeded, ${failures.length} failed. ` +
      `Catalogue now holds ${mergedItems.length} pieces. Credits this run: ${totalCredits}`,
  );
  if (failures.length) console.log(`Failed pieces (rerun individually or fall back to a sourced asset): ${failures.map((item) => `${item.type}/${item.style}`).join(", ")}`);
  console.log(`Manifest: ${MANIFEST_PATH}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
